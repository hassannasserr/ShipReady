import { useMemo, useState } from "react";
import {
  AlertTriangle,
  CheckCircle2,
  ClipboardList,
  FileJson,
  FolderOpen,
  Gauge,
  Info,
  ShieldCheck,
  Timer,
  XCircle,
} from "lucide-react";

const STATUS_META = {
  passed: { label: "Passed", tone: "success", icon: CheckCircle2 },
  failed: { label: "Failed", tone: "danger", icon: XCircle },
  error: { label: "Error", tone: "danger", icon: AlertTriangle },
  not_verified: { label: "Not verified", tone: "warning", icon: Info },
  skipped: { label: "Skipped", tone: "muted", icon: Info },
};

function formatDuration(value) {
  if (typeof value !== "number") return "—";
  return value < 1000 ? `${Math.round(value)} ms` : `${(value / 1000).toFixed(2)} s`;
}

function formatDate(value) {
  if (!value) return "—";
  return new Intl.DateTimeFormat(undefined, {
    dateStyle: "medium",
    timeStyle: "short",
  }).format(new Date(value));
}

function StatusBadge({ status }) {
  const meta = STATUS_META[status] ?? STATUS_META.error;
  const Icon = meta.icon;
  return (
    <span className={`status-badge ${meta.tone}`}>
      <Icon size={15} strokeWidth={2.5} />
      {meta.label}
    </span>
  );
}

function EmptyState({ onLoad }) {
  return (
    <section className="empty-state panel">
      <div className="empty-icon">
        <FileJson size={28} />
      </div>
      <h2>Load a ShipReady report</h2>
      <p>
        Choose a <code>report.json</code> generated by the baseline or business
        command to inspect the run here.
      </p>
      <button className="primary-button" onClick={onLoad}>
        <FolderOpen size={17} />
        Choose report
      </button>
    </section>
  );
}

function ScenarioCard({ result }) {
  const [expanded, setExpanded] = useState(false);
  return (
    <article className="scenario-card">
      <div className="scenario-header">
        <div>
          <div className="scenario-title-row">
            <span className="scenario-id">{result.scenario_id}</span>
            <StatusBadge status={result.status} />
          </div>
          <p className="scenario-summary">{result.observed_behavior}</p>
        </div>
        <button className="text-button" onClick={() => setExpanded(!expanded)}>
          {expanded ? "Hide details" : "View details"}
        </button>
      </div>
      <div className="scenario-meta">
        <span>
          <Timer size={15} /> {formatDuration(result.duration_ms)}
        </span>
        <span>
          <ClipboardList size={15} /> {result.evidence?.length ?? 0} evidence items
        </span>
      </div>
      {expanded && (
        <div className="scenario-details">
          <div className="detail-block">
            <span className="detail-label">Expected behavior</span>
            <p>{result.expected_behavior}</p>
          </div>
          <div className="detail-block">
            <span className="detail-label">Observed behavior</span>
            <p>{result.observed_behavior}</p>
          </div>
          <div className="detail-block">
            <span className="detail-label">Reproduction steps</span>
            <ol>
              {(result.reproduction_steps ?? []).map((step, index) => (
                <li key={`${step}-${index}`}>{step}</li>
              ))}
            </ol>
          </div>
          <div className="detail-block">
            <span className="detail-label">Evidence</span>
            <div className="evidence-list">
              {(result.evidence ?? []).map((item) => (
                <div className="evidence-item" key={item.name}>
                  <strong>{item.name}</strong>
                  <code>{JSON.stringify(item.value, null, 2)}</code>
                </div>
              ))}
            </div>
          </div>
        </div>
      )}
    </article>
  );
}

function App() {
  const [report, setReport] = useState(null);
  const [fileName, setFileName] = useState("");
  const [error, setError] = useState("");

  const summary = useMemo(() => {
    const results = report?.results ?? [];
    return {
      total: results.length,
      passed: results.filter((item) => item.status === "passed").length,
      failed: results.filter((item) => ["failed", "error"].includes(item.status)).length,
      attention: results.filter((item) => ["not_verified", "skipped"].includes(item.status)).length,
    };
  }, [report]);

  function loadReport() {
    document.getElementById("report-picker").click();
  }

  async function handleFile(event) {
    const file = event.target.files?.[0];
    if (!file) return;
    try {
      const parsed = JSON.parse(await file.text());
      if (!parsed.metadata || !Array.isArray(parsed.results)) {
        throw new Error("This file is not a ShipReady report.");
      }
      setReport(parsed);
      setFileName(file.name);
      setError("");
    } catch (loadError) {
      setReport(null);
      setError(loadError.message);
    }
    event.target.value = "";
  }

  return (
    <div className="app-shell">
      <header className="topbar">
        <div className="brand">
          <div className="brand-mark"><ShieldCheck size={21} /></div>
          <div>
            <strong>ShipReady</strong>
            <span>Control room</span>
          </div>
        </div>
        <div className="topbar-actions">
          {fileName && <span className="file-name">{fileName}</span>}
          <button className="secondary-button" onClick={loadReport}>
            <FolderOpen size={16} />
            Load report
          </button>
          <input id="report-picker" type="file" accept=".json,application/json" onChange={handleFile} />
        </div>
      </header>

      <main className="content">
        <section className="hero">
          <div>
            <p className="eyebrow">Assessment dashboard</p>
            <h1>Know what is ready to ship.</h1>
            <p className="hero-copy">
              Inspect real ShipReady execution results, evidence, and reproduction steps in one place.
            </p>
          </div>
          {report && (
            <div className="run-status">
              <span>Run status</span>
              <StatusBadge status={report.metadata.status === "completed" ? "passed" : "error"} />
            </div>
          )}
        </section>

        {error && <div className="error-banner"><AlertTriangle size={17} /> {error}</div>}
        {!report ? (
          <EmptyState onLoad={loadReport} />
        ) : (
          <>
            <section className="stats-grid">
              <div className="stat-card"><span>Total checks</span><strong>{summary.total}</strong><Gauge size={20} /></div>
              <div className="stat-card success-card"><span>Passed</span><strong>{summary.passed}</strong><CheckCircle2 size={20} /></div>
              <div className="stat-card danger-card"><span>Needs attention</span><strong>{summary.failed}</strong><XCircle size={20} /></div>
              <div className="stat-card warning-card"><span>Unverified / skipped</span><strong>{summary.attention}</strong><Info size={20} /></div>
            </section>

            <section className="layout-grid">
              <div className="main-column">
                <div className="section-heading">
                  <div><p className="eyebrow">Execution results</p><h2>Scenario checks</h2></div>
                  <span className="result-count">{summary.total} results</span>
                </div>
                <div className="scenario-list">
                  {report.results.map((result) => <ScenarioCard key={result.scenario_id} result={result} />)}
                </div>
              </div>
              <aside className="side-column">
                <div className="panel run-details">
                  <div className="panel-heading"><h3>Run details</h3><FileJson size={18} /></div>
                  <dl>
                    <div><dt>Run ID</dt><dd className="mono">{report.metadata.run_id}</dd></div>
                    <div><dt>Started</dt><dd>{formatDate(report.metadata.started_at)}</dd></div>
                    <div><dt>Completed</dt><dd>{formatDate(report.metadata.completed_at)}</dd></div>
                    <div><dt>Configuration</dt><dd className="mono">{report.metadata.config_path}</dd></div>
                  </dl>
                </div>
                <div className="panel guidance-card">
                  <div className="panel-heading"><h3>What next?</h3><Info size={18} /></div>
                  <p>
                    Review every failed or unverified result before treating this run as ready. Open its details for evidence and reproduction steps.
                  </p>
                </div>
              </aside>
            </section>
          </>
        )}
      </main>
    </div>
  );
}

export default App;
